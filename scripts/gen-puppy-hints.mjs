/**
 * Generator for Puppy Rescue's hint pack
 * (`src/components/widgets/puppyRescue/rescueHints.ts`).
 *
 *   node scripts/gen-puppy-hints.mjs
 *
 * Runs the planner (`rescuePlanner.planLevel`) on every level and writes its
 * quickest 3-star route, compactly encoded (`encodeRoute`), keyed by level
 * id. The planner takes up to a few seconds on the hardest levels — too slow
 * to run on a phone when Hint is tapped — so the routes ship pre-computed.
 * Re-run after adding or tuning a level: the e2e sweep (`180-puppy-model`)
 * fails any level whose stored hint is missing or no longer replays to 3★.
 */
import { spawnSync } from 'node:child_process'
import { mkdtempSync, writeFileSync } from 'node:fs'
import { tmpdir } from 'node:os'
import { dirname, join } from 'node:path'
import { fileURLToPath, pathToFileURL } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const dir = 'src/components/widgets/puppyRescue'
const out = mkdtempSync(join(tmpdir(), 'puppy-'))
const built = spawnSync(
  'npx',
  ['esbuild', `${dir}/rescueModel.ts`, `${dir}/rescueLevels.ts`, `${dir}/rescuePlanner.ts`, '--bundle', '--format=esm', `--outdir=${out}`],
  { cwd: root, stdio: 'inherit' },
)
if (built.status !== 0) process.exit(built.status ?? 1)
const { parseLevel, encodeRoute } = await import(pathToFileURL(join(out, 'rescueModel.js')).href)
const { LEVELS } = await import(pathToFileURL(join(out, 'rescueLevels.js')).href)
const { planLevel } = await import(pathToFileURL(join(out, 'rescuePlanner.js')).href)

const lines = []
for (const spec of LEVELS) {
  const plan = planLevel(parseLevel(spec))
  if (!plan) {
    console.error(`${spec.id}: no 3-star route — fix the level first`)
    process.exit(1)
  }
  lines.push(`  '${spec.id}': '${encodeRoute(plan.route)}',`)
  console.error(`${spec.id}: ${plan.route.length} steps, ${plan.time.toFixed(1)} s`)
}
writeFileSync(
  join(root, dir, 'rescueHints.ts'),
  `/**
 * GENERATED by \`node scripts/gen-puppy-hints.mjs\` — do not edit by hand.
 * Each level's quickest proven 3-star route (the planner's), in
 * \`decodeRoute\` form, for the 💡 Hint replay. The e2e sweep re-proves every
 * entry replays to 3★ through the real \`step\`.
 */
export const HINTS: Readonly<Record<string, string>> = {
${lines.join('\n')}
}
`,
)
