/** Display label: "Sneak 3". */
export function levelLabel(index: number): string {
  const spec = LEVELS[index]
  const n = LEVELS.slice(0, index + 1).filter((l) => l.tier === spec.tier).length
  return `${TIER_LABEL[spec.tier]} ${n}`
}
